"""Фабрики `callback_data` и разметка под них. ТЗ §19.1, §4.5.

Из трёх фабрик §19.1 — `Ans`, `Pick`, `Act` — объявлена **одна**, `Ans`:
`Pick` нужна двухтактному выбору соотнесений, `Act` — действиям «готово /
сброс / подсказка / источник / жалоба», и обе приезжают со своими типами
заданий в WP-14. Неиспользуемый класс — мёртвый код, а не задел.

`Retry` в этот счёт не входит: §19.1 перечисляет фабрики сеанса повторения, а
кнопка §4.5 к сеансу не относится. Прежняя редакция этой докстроки говорила
«объявлена одна» про весь модуль и стала ложной, когда фабрик стало две.

**Разметка живёт здесь, а не в хендлерах.** Клавиатуру под сообщение об
отказе собирает воркер (§4.5), и импортировать ради неё модуль хендлеров он
не должен: направление зависимости `worker → bot.handlers` затянуло бы в
фоновый процесс разбор апдейтов. Условие approve Плана PR 1b звучало именно
так, и держит его тест границы в `tests/test_layer_boundaries.py`.

`callback_data` ограничен 64 байтами на стороне Telegram, и это не
рекомендация: превышение даёт ошибку отправки. Проверяется тестом на
предельных значениях — сам aiogram длину не контролирует.
"""

from __future__ import annotations

from typing import Annotated, Final

from aiogram.filters.callback_data import CallbackData
from aiogram.types import InlineKeyboardButton, InlineKeyboardMarkup
from pydantic import Field

BIGINT_MAX: Final = 2**63 - 1
"""Предел `bigint` — типа ключей §3 (ADR-0004).

Нужен границей в схеме, а не проверкой в хендлере: `callback_data` приходит от
клиента, и `si` сверх этого предела доходил бы до запроса, где Postgres
отвечает `value out of range`. Исключение драйвера в хендлере выглядит сбоем
системы, а не отклонённым вводом.
"""

MAX_OPTION_INDEX: Final = 3
"""Наибольший индекс варианта MCQ. §9.2: «вариантов mcq не более 4».

Ограничение платформы, не качества, — но для разбора `callback_data` это
нижняя и верхняя граница допустимого `v`, и проверять её схемой дешевле, чем
ловить несуществующий вариант проверкой ответа.
"""

IDK: Final = -1
"""Значение `v`, означающее «не знаю». §19.1 дословно: «v = -1».

Константа, а не литерал по коду: минус единица в хендлере читается как
«неизвестный вариант», а это другой смысл — §13.2 различает «не знаю» и
«неверно», и на этой разнице стоят метрики §25.
"""


class Retry(CallbackData, prefix="r"):
    """Повторная обработка материала после отказа. §4.5.

    §4.5 требует кнопку прямо: «материал переводится в `failed` с понятной
    причиной; повторная обработка доступна кнопкой». Пункт именно §4.5, а не
    §4.1: в ТЗ эта фраза встречается один раз и стоит в абзаце про тайм-аут
    ожидания. Прежняя редакция ссылалась на §4.1, и ошибка была не
    косметической — она же скрыла, что путь тайм-аута остался без проверки
    кнопки (ревью PR #59). Отдельная фабрика, а не
    строка вида `retry:{id}`, по той же причине, по которой её имеет ответ на
    задание: границы значения объявлены схемой, и мусорный `callback_data`
    отклоняется `pydantic` раньше, чем дойдёт до запроса.

    Префикс `r` — один символ: §19.1 напоминает про предел 64 байта на
    `callback_data`, и при `bigint` в пределе это не теоретический запас.
    """

    material_id: Annotated[int, Field(gt=0, le=BIGINT_MAX)]


class Ans(CallbackData, prefix="a"):
    """Ответ на MCQ: номер элемента сессии и выбранный вариант.

    `si` — `session_items.id`, а не порядковый номер в сессии: порядковый
    номер не уникален между сессиями, и старая кнопка попала бы в задание
    нового сеанса. §38 №8 требует обратного — старый callback не должен
    менять данные, и для этого он обязан указывать на конкретную строку.

    """

    si: Annotated[int, Field(gt=0, le=BIGINT_MAX)]
    v: Annotated[int, Field(ge=IDK, le=MAX_OPTION_INDEX)]
    """Индекс варианта с нуля либо `IDK`.

    Границы объявлены схемой: `pydantic` отклонит значение раньше, чем оно
    дойдёт до запроса или до проверки ответа. Разбор мусорного
    `callback_data` — это `ValidationError`, а не `DBAPIError` в середине
    обработки.
    """


def retry_keyboard(material_id: int) -> InlineKeyboardMarkup:
    """Кнопка «Обработать заново» под сообщением об отказе. §4.5.

    Лежит рядом с фабрикой, а не в модуле хендлеров: разметку собирает воркер,
    и единственное, что ему для этого нужно, — `Retry`. Первая редакция
    держала её в `bot/handlers/retry.py`, воркер импортировал хендлеры, а
    докстрока при этом утверждала обратное — расхождение нашло ревью PR #59.
    """
    return InlineKeyboardMarkup(
        inline_keyboard=[
            [
                InlineKeyboardButton(
                    text="Обработать заново",
                    callback_data=Retry(material_id=material_id).pack(),
                )
            ]
        ]
    )
