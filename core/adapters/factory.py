"""Выбор адаптера по типу материала. ТЗ §5.1.

**Одна точка на весь проект.** Адаптер нужен раньше любой стадии: он параметр
гейта бюджета (`core/ingest/gate.py`), потому что §6.3 требует оценки до
`extract`. Стадия получает уже готовый `ctx.adapter` и ничего не выбирает.
Первая редакция плана WP-06 называла выбор в двух местах — в стадии и в
воркере, — и ревью показало, что стадия выбирать не может по построению.

Второго соответствия «тип → адаптер» в проекте быть не должно по той же
причине, по которой `ANSWERABLE_TYPES` выведено из реестра обработчиков
(ADR-0006): два списка расходятся, и расхождение видно не сразу, а на
материале, который молча не обработался.
"""

from __future__ import annotations

from pathlib import Path
from typing import Final

from core.adapters.base import SourceAdapter
from core.adapters.pdf import PdfAdapter
from core.config import Settings

TEXT_KIND: Final = "text"
"""Материал, который читается как текст.

Адаптера в `core/adapters` у него нет — его разбирает сам харнесс на
конспектах, подготовленных вручную (§2.1, CR-H).
"""

IMAGE_KIND: Final = "image"
"""§5.3. Адаптер приедет в PR C пакета WP-06; тип уже пишется в базу при приёме."""

BY_EXTENSION: Final[dict[str, str]] = {
    ".pdf": "pdf",
    ".md": TEXT_KIND,
    ".txt": TEXT_KIND,
    ".jpg": IMAGE_KIND,
    ".jpeg": IMAGE_KIND,
    ".png": IMAGE_KIND,
    ".webp": IMAGE_KIND,
}
"""Расширение файла → `materials.kind` (§3). **Единственная** такая карта.

До правки по замечанию ревью PR #42 соответствие выводилось в двух местах — в
`bot/handlers/upload.py` по имени файла и здесь, — и они уже расходились:
`photo-ab12cd34.jpg` давал `kind = "image"` при приёме и `text` здесь, то есть
воркер выбирал адаптер не для того типа, что записан в базе. Не ломалось
только потому, что адаптера изображений ещё нет. Прецедент против второго
реестра — ADR-0006 (`ANSWERABLE_TYPES` выведено из реестра обработчиков).

Аудио и видео приедут со своими адаптерами в WP-19 и WP-20.
"""


def kind_for_path(path: str) -> str:
    """Тип материала по расширению. Неизвестное расширение — `text`.

    Откат к `text`, а не отказ: это путь харнесса (`make seed`), где на входе
    конспект без расширения или с любым другим, и читать его как текст —
    штатное поведение. Приём файла из чата пользуется `known_kind_for_path`:
    там неизвестное расширение обязано получать внятный отказ, а не молча
    становиться текстом.
    """
    return BY_EXTENSION.get(Path(path).suffix.lower(), TEXT_KIND)


def known_kind_for_path(path: str) -> str | None:
    """Тип материала только для известных расширений, иначе `None`.

    `None` означает «здесь не поддерживается» и превращается в отказ §19.4 на
    приёме файла. Та же карта, что у `kind_for_path`, другая политика на
    неизвестном расширении — и обе политики названы, а не выведены дважды.
    """
    return BY_EXTENSION.get(Path(path).suffix.lower())


PENDING_KINDS: Final[dict[str, str]] = {
    IMAGE_KIND: "WP-06 PR C",
    "audio": "WP-19",
    "video": "WP-20",
}
"""Типы, которые §3 уже знает, а адаптера для них ещё нет — и в каком пакете он будет."""


def build_adapter(kind: str, *, settings: Settings) -> SourceAdapter | None:
    """Адаптер для типа материала или `None`, если его разбирает не адаптер.

    `None` **только** для текстового материала: его читает харнесс, и
    отдельного адаптера §5 для него не предусматривает. Это честнее
    исключения — иначе прогон конспекта через `make seed` падал бы на выборе
    адаптера.

    Тип, у которого адаптер ещё не приехал, даёт `ValueError` с именем пакета.
    Раньше он молча получал `None` и обрабатывался текстовой заглушкой: для
    изображения это означало материал без фрагментов и отказ стадии с причиной
    «обработать заново», из которой не видно, что тип просто не поддержан.
    """
    if kind == "pdf":
        return PdfAdapter(settings=settings)
    if kind == TEXT_KIND:
        return None
    if kind in PENDING_KINDS:
        raise ValueError(f"адаптер для материалов типа {kind!r} приедет в {PENDING_KINDS[kind]}")
    raise ValueError(f"неизвестный тип материала: {kind!r}")
