"""Интерфейс источника. ТЗ §5.1.

```python
class SourceAdapter(ABC):
    kind: str
    async def probe(self, path: str) -> SourceMeta: ...
    def extract(self, path: str, ctx: IngestCtx) -> AsyncIterator[Fragment]: ...
    def assets(self, path: str, ctx: IngestCtx) -> AsyncIterator[ExtractedAsset]: ...
```

§5.1 (v3.17): «Новый тип источника = адаптер + вариант `Locator`. Третий метод
**необязательный**… Больше ничего не меняется». Поэтому здесь нет ничего,
кроме контракта: ни PDF, ни аудио, ни зависимостей от них. Реализации
появляются по пакетам — PDF в WP-06, аудио в WP-19, видео в WP-20.

Третий метод появился решением Архитектора 2026-10-15 (Issue #38) и ослабил
прежнюю формулировку «больше ничего не меняется» — цена названа в §5.1 прямо.
Повод: изображение сохраняется в `media_assets` и тогда, когда описания у него
ещё нет, а значит нет и фрагмента (§5.2 п. 4 v3.17), — то есть носителем
ассета фрагмент быть перестал.

`probe` отделён от `extract` не для удобства, а по требованию §6.3: оценка
стоимости считается **до** `extract`, потому что для сканированного PDF
`extract` — это vision-вызов на каждую страницу, то есть основная статья
расхода. Гейт после него спрашивал бы «обрабатывать?» после того, как деньги
потрачены.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from collections.abc import AsyncIterator
from dataclasses import dataclass, field
from typing import Any


@dataclass(frozen=True)
class SourceMeta:
    """Результат `probe` — то, из чего §6.3 строит предварительную оценку.

    Поля необязательны по природе источника: у PDF есть страницы и нет
    длительности, у аудио наоборот. Пустой `SourceMeta` допустим и означает
    «ничего измерить не удалось» — тогда оценка строится по размеру файла, а
    не выдумывается.
    """

    pages: int | None = None
    duration_sec: float | None = None
    text_chars: int | None = None
    vision_pages_ratio: float = 0.0
    """Доля страниц, требующих vision (§5.2). Главный множитель стоимости:
    страница с текстовым слоем стоит на порядок меньше сканированной."""
    extra: dict[str, Any] = field(default_factory=dict)
    """То, что пойдёт в `materials.origin` — `pages`, `duration`, `youtube_id`
    и прочее по §3. Словарь, а не поля, потому что состав зависит от типа
    источника, а §3 объявляет `origin` как JSONB."""


@dataclass(frozen=True)
class IngestCtx:
    """Контекст извлечения, который адаптер получает, но не формирует сам."""

    material_id: int
    tmp_dir: str
    """`.tmp/<material_id>/<stage>/` (§4.2). Адаптер пишет медиа только сюда:
    перенос в постоянное хранилище делается после коммита стадии, иначе на
    диске остаются артефакты формально не выполненной стадии."""


@dataclass(frozen=True)
class ExtractedFragment:
    """Фрагмент до записи в базу.

    Не модель `core.db.models.Fragment` намеренно: адаптер не должен знать ни
    про SQLAlchemy, ни про идентификаторы. §5.1 называет возвращаемый тип
    `Fragment`, но связывать адаптеры со слоем данных значило бы, что новый
    тип источника меняет не только адаптер.
    """

    ord: int
    kind: str
    """text|transcript|slide|image (§3)."""
    locator: dict[str, Any]
    """§3.4. Обязателен: без локатора фрагмент не даёт перехода к источнику."""
    text: str | None = None
    asset_path: str | None = None
    """Путь во временной директории, если фрагмент — изображение."""
    quality: float = 1.0
    """0..1. Множитель `final_confidence` (§7.3), тип хранения `REAL` (§3)."""
    tokens: int | None = None


@dataclass(frozen=True)
class ExtractedAsset:
    """Медиафайл до записи в базу. §5.2 п. 4, §5.3.

    Не модель `core.db.models.MediaAsset` по той же причине, по которой
    `ExtractedFragment` не модель `Fragment`: адаптер не знает ни про
    SQLAlchemy, ни про идентификаторы.

    `page`, `area_ratio` и `group_id` базе напрямую не нужны — колонок под них
    в `media_assets` нет (§3), и это осознанно: постоянное место группы —
    локатор фрагмента (§3.4, решение Архитектора 2026-10-14). До появления
    фрагмента они едут в `materials.origin` как измерение, и это долг с
    владельцем: его закрывает PR C2 пакета WP-06.
    """

    path: str
    """Путь во временной директории стадии (§4.2). Постоянный путь выбирает
    стадия: адаптер о постоянном хранилище не знает."""
    mime: str
    width: int
    height: int
    caption: str | None = None
    """Подпись, если нашлась: по ней работает правило набора §5.2 п. 4."""
    page: int | None = None
    """Человеческий номер страницы, с единицы. `None` у источников без страниц."""
    area_ratio: float | None = None
    """Доля площади страницы. Сравнивается с `MIN_IMAGE_AREA_RATIO` (§30.3)."""
    group_id: str | None = None
    """Непустой у изображений набора «Рис. N» (§5.2 п. 4)."""


class SourceAdapter(ABC):
    """Источник материала."""

    kind: str
    """pdf|image|audio|video|web|text — значение `materials.kind` (§3)."""

    @abstractmethod
    async def probe(self, path: str) -> SourceMeta:
        """Измеряет источник, не обрабатывая его.

        Должен быть дешёвым: вызывается до гейта бюджета, то есть до того, как
        пользователь согласился платить. Для PDF это чтение оглавления и
        проверка текстового слоя, не распознавание.
        """

    @abstractmethod
    def extract(self, path: str, ctx: IngestCtx) -> AsyncIterator[ExtractedFragment]:
        """Разбирает источник на фрагменты.

        Асинхронный итератор, а не список: материал может дать тысячи
        фрагментов, и держать их все в памяти незачем. Сигнатура не
        `async def` — функция возвращает итератор, а не корутину.
        """

    async def assets(self, path: str, ctx: IngestCtx) -> AsyncIterator[ExtractedAsset]:
        """Медиафайлы источника. §5.1 v3.17: метод **необязательный**.

        Не `@abstractmethod`: источник без медиафайлов — текст, веб-страница —
        не обязан ничего переопределять, и пустая реализация здесь честнее
        заглушки в каждом таком адаптере.

        Отдельно от `extract`, потому что ассет живёт не только внутри
        фрагмента: изображение сохраняется в `media_assets` и тогда, когда
        описания у него ещё нет (§5.2 п. 4 v3.17). Файлы пишутся **только** в
        `ctx.tmp_dir` (§4.2); постоянный путь выбирает стадия.

        Пустая реализация написана перебором пустого кортежа, а не `return` с
        недостижимым `yield`: `yield` нужен, чтобы метод был асинхронным
        итератором, а не корутиной (та же разница, о которой сказано у
        `extract`), но недостижимую строку запрещает `warn_unreachable`
        (§35, `pyproject.toml`). Подавление здесь было бы костылём п. 6 ради
        стиля.
        """
        empty: tuple[ExtractedAsset, ...] = ()
        for asset in empty:
            yield asset
