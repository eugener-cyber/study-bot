"""Интерфейс провайдера модели. ТЗ §2.1.

§2.1 задаёт его так:

```python
class LLMProvider(ABC):
    name: str

    async def structured(
        self, prompt: str, schema: type[BaseModel], *, purpose: str
    ) -> BaseModel: ...

    async def vision(
        self, images: list[ImageInput], prompt: str,
        schema: type[BaseModel], *, purpose: str
    ) -> BaseModel: ...
```

и тут же требует: «Оба метода возвращают не только разобранную модель, но и
фактические счётчики токенов и стоимость вызова: без них §6.4 нечем наполнять,
а оценка §6.3 не с чем сравнивать».

**Подпись и текст §2.1 друг другу не соответствуют**: `-> BaseModel` не несёт
счётчиков. Следую тексту, а не подписи, — текст называет причину, подпись
выглядит сокращением записи. Возвращается `LLMResult`: разобранная модель
плюс токены. Стоимость считает **клиент**, а не провайдер: §2.1 говорит
«запись в `llm_calls` выполняет клиент», и цена — свойство тарифа, а не
вызова.

Отмечаю расхождение здесь, а не оформляю change request: §2.1 не содержит двух
противоречащих требований — он содержит требование и его неполную запись.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass

from pydantic import BaseModel


@dataclass(frozen=True)
class ImageInput:
    """Изображение для vision-вызова (§5.2, §5.3).

    Путь, а не байты: при `TELEGRAM_LOCAL=1` файл уже лежит на диске (§2.2), и
    загружать его в память ради передачи провайдеру незачем — страница скана
    это мегабайты, а их на материал бывают сотни.
    """

    path: str
    mime: str = "image/png"


@dataclass(frozen=True)
class TokenUsage:
    """Фактические счётчики вызова.

    `estimated` отличает оценку от факта. У провайдера `manual` вызова не
    было, и его числа — оценка по длине текста (§2.1 после решения
    Архитектора); у настоящего провайдера приходят из ответа. §6.4 сравнивает
    оценку с фактом, и смешать их значило бы сравнивать оценку с собой.
    """

    input_tokens: int
    output_tokens: int
    estimated: bool = False

    @property
    def total(self) -> int:
        return self.input_tokens + self.output_tokens


@dataclass(frozen=True)
class LLMResult[T: BaseModel]:
    """Что провайдер возвращает: разобранная модель и счётчики."""

    value: T
    usage: TokenUsage
    model: str
    """Имя модели, попадающее в `llm_calls.model` (§3). У `manual` — метка
    режима, а не модели: `manual` вызовов не делает, и писать туда имя
    настоящей модели значило бы утверждать, что она отвечала."""


class ProviderError(Exception):
    """Ошибка вызова, которая **уже стоила токенов**.

    Общий предок двух правил ретраев §6.1 существует ради одного поля:
    `usage`. Негодный ответ модели оплачен так же, как годный, и §6.4 обязан
    учесть его — «платить приходится за все». Провайдер, который знает
    фактические счётчики отказа, кладёт их сюда; клиент, не получив их,
    считает расход по оценке входа и помечает строку `ok = false`.
    """

    def __init__(self, message: str, *, usage: TokenUsage | None = None) -> None:
        super().__init__(message)
        self.usage = usage


class SchemaError(ProviderError):
    """Ответ не разобрался по схеме.

    Отдельный тип, потому что §6.1 назначает ему **другое** правило ретраев,
    чем сетевым ошибкам: один повтор с приклеенным текстом ошибки, затем
    `failed`. Сетевая ошибка проходит сама, а ошибка схемы означает, что
    модель не поняла задачу, и четыре попытки сожгут бюджет на четыре
    одинаково негодных ответа.
    """


class ProviderUnavailableError(ProviderError):
    """Провайдер ответил 429 или 5xx.

    §6.1: экспоненциальный backoff, до четырёх попыток. Отличается от
    `SchemaError` именно тем, что повтор имеет смысл.

    Суффикс `Error` обязателен (`N818`) и, в отличие от `AwaitingUser` из
    WP-03, здесь не подавляется: `AwaitingUser` несёт штатное ветвление —
    обработка приостановлена и ждёт человека, — а недоступность провайдера
    это именно сбой.
    """


class LLMProvider(ABC):
    """Провайдер модели. §2.1: реализация одна на инсталляцию."""

    name: str
    """Значение `llm_calls.provider` (§3): `anthropic` | `yandexgpt` | `manual`."""

    offline: bool = False
    """Провайдер не обращается к сети.

    Нужно клиенту для режима `replay` (§1.5 Плана). Смысл режима — «тесты не
    ходят в сеть», и для сетевого провайдера клиент подменяет вызов чтением
    записи. Для `manual` подменять нечего: он и так читает файлы, причём
    **свой** каталог на томе §30.1 раньше `tests/golden`. Если бы клиент
    перехватывал и его, подготовленное руками содержание в режиме по
    умолчанию игнорировалось бы — то есть продукт в своём штатном режиме не
    видел бы собственных данных.
    """

    @abstractmethod
    async def structured[T: BaseModel](
        self, prompt: str, schema: type[T], *, purpose: str
    ) -> LLMResult[T]:
        """Структурированный вывод по строгой схеме (§6.1).

        §6.1: «через механизм structured output провайдера со строгой схемой;
        парсинг свободного текста только как запасной путь». Поэтому схема —
        обязательный параметр, а не подсказка: ответ, не разобравшийся по ней,
        поднимает `SchemaError`, а не возвращается как есть.
        """

    @abstractmethod
    async def vision[T: BaseModel](
        self,
        images: list[ImageInput],
        prompt: str,
        schema: type[T],
        *,
        purpose: str,
    ) -> LLMResult[T]:
        """То же для изображений (§5.2, §5.3).

        Отдельный метод, а не флаг у `structured`: §2.1 задаёт `LLM_MODEL` и
        `LLM_VISION_MODEL` отдельными переменными, то есть модель может
        различаться, и выбор её — дело провайдера.
        """
