"""Объёмы и цены вызовов модели. ТЗ §2.1, §6.3, §6.4.

Три знания в одном месте, потому что их используют два потребителя: клиент
LLM (§6.4, оценка и факт по каждому вызову) и оценка бюджета материала (§6.3,
гейт до стадии `extract`).

- сколько токенов в тексте,
- сколько выхода производит стадия,
- сколько стоит токен у провайдера.

**Почему здесь, а не в `core/ingest/budget.py`.** Таблица коэффициентов жила
там, и клиенту пришлось бы импортировать из `core/ingest` — то есть слой LLM
зависел бы от пакета обработки материала, который его потребитель. В WP-10 и
WP-11 валидатор §11.4 и судья §21.3 потянули бы `core/ingest` за собой, не
имея к обработке материала отношения. Направление `ingest → llm` правильное:
оценка стоимости материала законно зависит от цен и объёмов вызовов модели.

Ревью плана предлагало вместо переноса передавать коэффициенты параметром.
Решено иначе: порог обучаемости — одно число из конфигурации, и параметр там
естествен, а это таблица по назначениям вызова, то есть свойство самих стадий.
Передача через каждую точку вызова означала бы повтор в четырёх стадиях, в
валидаторе и в судье, и первая забытая передача дала бы оценку по умолчанию
**молча**, потому что умолчание существует.
"""

from __future__ import annotations

from dataclasses import dataclass
from decimal import Decimal

CHARS_PER_PAGE = 2500
"""Плотная страница A4 учебного текста."""

CHARS_PER_TOKEN_CYRILLIC = 5.0
"""Символов на токен для русского текста.

Число согласовано с `core/ingest/budget.py` из WP-03, где оно выведено из
размера страницы. План WP-04 в редакции 2 предлагал 2.5, то есть вдвое
меньше, — расхождение нашло ревью. Взято значение WP-03: оно уже в работе,
прошло ревью и участвует в оценках существующих материалов, а 2.5 было
предположением без обоснования лучше прежнего.

**Оценка, не точный счёт.** Точное число даёт токенизатор модели, которого без
ключа провайдера нет. Погрешность укладывается в коридор 0.4, который §6.4
требует от расхождения оценки с фактом, и при появлении ключа оценка
заменяется точным счётом — то есть коэффициент исчезает, а не уточняется.
"""

CHARS_PER_TOKEN_LATIN = 4.0
"""Для латиницы токены крупнее: меньше символов на токен."""


def tokens_in(text: str) -> int:
    """Оценка числа токенов в тексте.

    Коэффициент выбирается по доле кириллицы, а не по языку материала: в
    учебном тексте перемешаны термины, формулы и латинские обозначения, и
    один коэффициент на весь текст давал бы систематический перекос в сторону
    того алфавита, которого в примере оказалось больше.
    """
    if not text:
        return 0

    cyrillic = sum(1 for char in text if "Ѐ" <= char <= "ӿ")
    share = cyrillic / len(text)
    chars_per_token = CHARS_PER_TOKEN_CYRILLIC * share + CHARS_PER_TOKEN_LATIN * (1 - share)
    return max(round(len(text) / chars_per_token), 1)


def tokens_per_page() -> int:
    """Токенов на странице плотного русского текста.

    Выводится из `CHARS_PER_TOKEN_CYRILLIC`, а не задаётся отдельно: два
    независимых числа для одного и того же разошлись бы, и §6.3 оценивал бы
    материал по одному, а §6.4 те же вызовы по другому — коридор приёмки
    показал бы расхождение там, где его нет.
    """
    return round(CHARS_PER_PAGE / CHARS_PER_TOKEN_CYRILLIC)


@dataclass(frozen=True)
class StageCoefficients:
    """Расход токенов по стадиям. **Предварительные значения.**

    Каждое число — оценка сверху с выводом, а не угаданное. Уточняются спайком
    (§34.1) и после него переезжают в §30.3 — см. CR-I, Issue #13.
    """

    text_tokens_per_page: int = 500
    """Страница учебного текста. Равно `tokens_per_page()`; согласованность
    закреплена тестом, иначе второе число вернётся при первой правке."""

    vision_input_per_page: int = 1600
    """Сканированная страница в vision-вызове: изображение занимает порядка
    1500 токенов входа плюс промпт. Главный множитель стоимости — §5.2."""

    vision_output_per_page: int = 500
    """Распознанный текст страницы на выходе."""

    audio_tokens_per_minute: int = 150
    """Минута речи в транскрипте: около 130 слов, около 1.2 токена на слово."""

    sections_output_ratio: float = 0.05
    """Выход стадии `sections` к объёму входа: заголовки и границы."""

    facts_output_ratio: float = 0.30
    """Выход стадии `facts`: утверждение и разбор на каждый факт."""

    questions_output_ratio: float = 0.60
    """Выход стадии `questions`: два-четыре задания на факт с дистракторами —
    самая многословная стадия."""

    def output_ratio_for(self, purpose: str) -> float:
        """Доля выхода для назначения вызова.

        Назначение приходит строкой, потому что им же помечается строка в
        `llm_calls` (§3, поле `purpose`). Неизвестное назначение даёт
        исключение, а не умолчание: умолчание дало бы оценку, похожую на
        правильную, и расхождение в §6.4 искали бы в ценах.
        """
        ratios = {
            "sections": self.sections_output_ratio,
            "facts": self.facts_output_ratio,
            "questions": self.questions_output_ratio,
        }
        # `notes` здесь нет, и это решение Архитектора v3.13 (CR-O, #26):
        # конспект §8 рендерится из сохранённых фактов, модель на нём не
        # вызывается. Оставить коэффициент значило бы держать оценку расхода
        # для вызова, которого не бывает, — и первые реальные материалы
        # показали бы систематическое завышение, причину которого искали бы
        # в ценах.
        if purpose not in ratios:
            raise ValueError(
                f"неизвестное назначение вызова: {purpose!r}; " f"известные: {sorted(ratios)}"
            )
        return ratios[purpose]


@dataclass(frozen=True)
class ProviderPrices:
    """Цены за миллион токенов."""

    input_per_million: Decimal
    output_per_million: Decimal

    def cost(self, input_tokens: int, output_tokens: int) -> Decimal:
        million = Decimal(1_000_000)
        return (
            Decimal(input_tokens) * self.input_per_million / million
            + Decimal(output_tokens) * self.output_per_million / million
        )


PRICING_VERSION = "2026-10-anthropic-opus5"
"""Версия тарифов, попадающая в `llm_calls.pricing_version` (§3, §6.4).

Строка с датой и моделью, а не номер: поле отвечает на вопрос «по каким ценам
посчитана эта строка» без обращения к истории git.

**Меняется вместе с `PRICES`.** Правка цен без правки версии пометила бы всю
историю `llm_calls` неверно, то есть сделала бы бесполезным именно то поле,
ради которого §3 его завёл. Против этого стоит тест, где и версия, и числа
записаны литералами: смена любого требует правки теста, и правка видна в
диффе.
"""

PRICES: dict[str, ProviderPrices] = {
    # §2.1: $5 / $25 за млн токенов (вход / выход) на `claude-opus-5`.
    "anthropic": ProviderPrices(Decimal("5"), Decimal("25")),
    # §2.1 после решения Архитектора: токены — оценка, стоимость — ноль,
    # потому что вызова не было. Отсюда следствие, разобранное в ADR-0005:
    # коридор §6.4 считается на токенах, а не на стоимости.
    "manual": ProviderPrices(Decimal("0"), Decimal("0")),
    # YandexGPT — тарифы по §2.1 «по тарифам Яндекса», числа появятся вместе
    # с провайдером. Запись отсутствует намеренно: нуль здесь выглядел бы
    # бесплатным провайдером.
}


def prices_for(provider: str) -> ProviderPrices:
    """Цены провайдера. Неизвестный провайдер — исключение, не нули.

    Нули для неизвестного означали бы бесплатные вызовы, и §6.4 показывал бы
    нулевой расход при реально потраченных деньгах. Лучше падение на старте.
    """
    if provider not in PRICES:
        raise ValueError(f"нет тарифов для провайдера {provider!r}; известные: {sorted(PRICES)}")
    return PRICES[provider]
