#!/bin/sh
# Бот и ARQ-воркер — два процесса одного контейнера.
#
# §30.1 ТЗ называет ровно четыре контейнера, а §1.4 уточняет: «бот и ARQ-воркер
# как два процесса одного образа». Пятый сервис compose дал бы пятый контейнер,
# то есть расхождение со спецификацией — ровно того рода, какое в WP-02
# пришлось выносить отдельным change request (CR-G, пятый том).
#
# `wait -n` завершает скрипт, как только упадёт ЛЮБОЙ из двух процессов.
# Без него контейнер оставался бы «живым» с одним работающим процессом:
# бот отвечал бы на сообщения, а материалы не обрабатывались — и compose
# не перезапустил бы ничего, потому что контейнер формально работает.
set -e

python -m arq worker.WorkerSettings &
WORKER_PID=$!

python -m bot.main &
BOT_PID=$!

echo "запущены: воркер pid=$WORKER_PID, бот pid=$BOT_PID"

wait -n
EXIT_CODE=$?
echo "один из процессов завершился с кодом $EXIT_CODE — останавливаю контейнер"
kill "$WORKER_PID" "$BOT_PID" 2>/dev/null || true
exit "$EXIT_CODE"
